import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { isDeliveryCurrentForReport, reportIsQualitative, RESULT_REPORT_SECTION_TITLES } from '../src/data/resultReportPresentation.js';

test('report presentation uses the professional team-facing sections', () => {
  assert.deepEqual(Object.values(RESULT_REPORT_SECTION_TITLES), [
    'Executive Summary',
    'What You Did Well',
    'Where You Can Improve',
    'Why This Matters',
    'Actionable Recommendations',
    'Priority Areas',
    'Judge Feedback Summary',
    'Final Remarks',
  ]);
});

test('numeric evaluation content is excluded from report preview', () => {
  const report = {
    summary: 'The project is thoughtful.', strengths: ['Clear user research.'],
    weaknesses: ['The project requires more testing.'], whyThisMatters: 'Testing evidence helps reviewers trust reliability.',
    improvementSuggestions: ['Document the validation process.'],
    priorityAreas: ['High Priority: Add edge-case tests.'], judgeFeedbackSummary: 'Judges valued the concept.', finalRemarks: 'Continue refining the work.',
  };
  assert.equal(reportIsQualitative(report), true);
  assert.equal(reportIsQualitative({ ...report, finalRemarks: 'The final score was 92.' }), false);
  assert.equal(reportIsQualitative({ ...report, summary: 'The team ranked first.' }), false);
  assert.equal(reportIsQualitative({ ...report, finalRemarks: 'AI Generated: keep refining the work.' }), false);
});

test('delivery status is compared with the saved report generation time', () => {
  const report = { reportId: 'report-1', generatedAt: '2026-10-23T10:00:00.000Z' };
  assert.equal(isDeliveryCurrentForReport({ reportId: 'report-1', createdAt: '2026-10-23T10:01:00.000Z' }, report), true);
  assert.equal(isDeliveryCurrentForReport({ reportId: 'report-1', createdAt: '2026-10-23T09:59:00.000Z' }, report), false);
  assert.equal(isDeliveryCurrentForReport({ reportId: 'report-2', createdAt: '2026-10-23T10:01:00.000Z' }, report), false);
});

test('result report page contains no AI attribution labels', async () => {
  const page = await readFile(new URL('../src/pages/OrganizerResultReports.jsx', import.meta.url), 'utf8');
  const workspace = await readFile(new URL('../src/pages/OrganizerEventWorkspace.jsx', import.meta.url), 'utf8');
  assert.doesNotMatch(`${page}\n${workspace}`, /AI\s*[- ]?generated|generated by AI|AI Result Reports|Generate AI Report|Generated with \{report\.model\}/i);
});

test('result report page scopes management actions and previews to one selected team', async () => {
  const page = await readFile(new URL('../src/pages/OrganizerResultReports.jsx', import.meta.url), 'utf8');
  for (const label of ['View Report', 'Send Report', 'Send to Selected Teams', 'Not Sent', 'Sending', 'Sent', 'Partially Sent', 'Failed']) {
    assert.ok(page.includes(label), `missing report delivery UI label: ${label}`);
  }
  assert.match(page, /const \[selectedTeamId, setSelectedTeamId\]/);
  assert.match(page, /disabled=\{selectedTeamId !== teamId \|\| !completed \|\| workingTeamIds\.includes\(teamId\)\}/);
  assert.match(page, /disabled=\{selectedTeamId !== teamId \|\| !eligible \|\| isSending/);
  assert.match(page, /previewTeamId === selectedTeamId/);
  assert.match(page, /requestEventId\.current !== eventAtStart/);
  assert.match(page, /disabled=\{!selectedTeamIds\.length \|\| bulkSending/);
});
